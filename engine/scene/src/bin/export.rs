use openmars_scene::{
    SceneEvent, ScenePlayer, SceneSnapshot, SceneTile, SceneTileBonus, SceneTileVisual,
    offworld::{OffworldScene, SceneColony, SceneFleet, SceneStation},
    presentation::{SceneSound, SoundAction, SoundKind},
    structure::StructureStyleRequest,
};
use openmars_scene::{
    assets::{AssetDemand, AssetKind, AssetRequirement},
    view::{
        AssetView, BodyId, BodyMarker, FocusTarget, GraphicsSettings, MenuPlacement, OverlayFrame,
        Quality, StationMarker, TileEntry, WorldEntry, WorldLight,
    },
};
use ts_rs::TS;
fn main() {
    let output = format!(
        "// Generated by openmars-scene; do not edit.\n\nexport {}\n\nexport const rendererAssets = {} as const;\n\nexport const gameAssets = {} as const;\n\nexport const menuAssets = {} as const;\n\nexport const MAX_ASSET_FILE_BYTES = {};\nexport const DISPLAY_SKY_FILE_BYTES = {};\nexport const SCENE_ASSET_CACHE_BYTES = {};\n",
        [
            AssetKind::decl(),
            AssetRequirement::decl(),
            AssetDemand::decl(),
            AssetView::decl(),
            Quality::decl(),
            GraphicsSettings::decl(),
            MenuPlacement::decl(),
            TileEntry::decl(),
            WorldLight::decl(),
            WorldEntry::decl(),
            BodyId::decl(),
            FocusTarget::decl(),
            BodyMarker::decl(),
            StationMarker::decl(),
            OverlayFrame::decl(),
            StructureStyleRequest::decl(),
            SceneTileVisual::decl(),
            SceneTileBonus::decl(),
            SceneTile::decl(),
            ScenePlayer::decl(),
            SceneSnapshot::decl(),
            OffworldScene::decl(),
            SceneColony::decl(),
            SceneFleet::decl(),
            SceneStation::decl(),
            SceneEvent::decl(),
            SoundKind::decl(),
            SoundAction::decl(),
            SceneSound::decl()
        ]
        .join("\n\nexport "),
        serde_json::to_string(&openmars_scene::assets::RENDERER_ASSETS).unwrap(),
        serde_json::to_string(&openmars_scene::assets::requirements(AssetView::Game)).unwrap(),
        serde_json::to_string(&openmars_scene::assets::requirements(AssetView::Menu)).unwrap(),
        openmars_scene::assets::MAX_ASSET_FILE_BYTES,
        openmars_scene::assets::DISPLAY_SKY_FILE_BYTES,
        openmars_scene::assets::SCENE_ASSET_CACHE_BYTES
    );
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../frontend/src/engine/scene.generated.ts");
    if std::env::args().any(|arg| arg == "--check") {
        assert_eq!(
            std::fs::read_to_string(&path).expect("Generate scene types first"),
            output,
            "Scene types are stale"
        );
    } else {
        std::fs::write(path, output).unwrap();
    }
}
